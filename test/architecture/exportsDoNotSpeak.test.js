// @vitest-environment node
/**
 * F98 (UAT-308, REQ-06): the two export services and the model of the album load write no sentence of their own. They give a code and
 * the data (a kind of failure, a step of the progress, a reason of a hold); the window, or a file of i18n/, says the words in the language
 * the app speaks. This test reads the source of the three files and fails on any text literal that reads as a sentence: two words or
 * more, with a space between them, or one word written as a sentence begins (a capital letter, then small ones: «Connecting...»).
 *
 * What a sentence may still be, and is not accused:
 *   - what goes to the console (`console.*(...)`): the person never reads it;
 *   - the message of an error that is thrown (`new Error(...)`): the caller acts on the error, the screen does not show it;
 *   - what is listed in WRITTEN_ELSEWHERE, each with its reason.
 *
 * What it does NOT prove: that every sentence on the screen is in the dictionary (the two windows are read in both languages by their own
 * tests and by the browser proof), nor that other services write no sentence (they are not in the list of FILES).
 */
import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'
import { parseSource } from './support/parseSource.js'

const FILES = [
    'public/js/services/SpotifyExportService.js',
    'public/js/services/AppleMusicExportService.js',
    'public/js/models/albumLoadState.js'
]

/** Sentences these files may write, because they are not shown by the app. The list can only shrink. */
const WRITTEN_ELSEWHERE = Object.freeze({
    'public/js/services/SpotifyExportService.js': {
        'Part of {}': 'the description of the playlist, written INTO Spotify (the person reads it there, beside a name they typed); it has been in English since F62 and the playlists already exported carry it',
        'Generated by MJRP Album Blender • {}/{} tracks': 'the description of the playlist, written INTO Spotify; same reason'
    }
})

const WORD = '[A-Za-zÀ-ÿ]{2,}'
/**
 * Two words with a space between them, or a text that begins as a sentence does: a capital letter, then small ones («Connecting...»).
 * The name of a class («DeadlineError») is not a word: another capital follows.
 */
const SENTENCE = new RegExp(`${WORD}[,:;.!?]?\\s+${WORD}|^[A-ZÀ-Ý][a-zà-ÿ]+(?![A-Za-z0-9_])`)

/** The text of a literal as it is written: a template with its holes shown as {}. */
function textOf(node) {
    if (node.type === 'Literal') return typeof node.value === 'string' ? node.value : null
    if (node.type === 'TemplateLiteral') return node.quasis.map(quasi => quasi.value.cooked).join('{}')
    return null
}

const isConsoleCall = (node) => node.type === 'CallExpression' && node.callee.type === 'MemberExpression' && node.callee.object.name === 'console'
const isErrorMade = (node) => node.type === 'NewExpression' && /Error$/.test(node.callee.name || '')
const isModuleName = (node) => node.type === 'ImportDeclaration' || node.type === 'ImportExpression' || node.type === 'ExportNamedDeclaration' || node.type === 'ExportAllDeclaration'

/**
 * The sentences a source writes by itself, each with its line.
 * @param {string} source
 * @param {Record<string, string>} [allowed] - text -> reason
 * @returns {string[]}
 */
export function sentencesIn(source, allowed = {}) {
    const found = []
    const walk = (node, quiet) => {
        if (!node || typeof node.type !== 'string') return
        if (isModuleName(node)) {
            // an `export const x = ...` is code like any other; only the name of the module is skipped
            if (node.declaration) walk(node.declaration, quiet)
            return
        }
        const silent = quiet || isConsoleCall(node) || isErrorMade(node)
        const text = textOf(node)
        if (text !== null && !silent && SENTENCE.test(text) && !Object.hasOwn(allowed, text)) found.push(`line ${node.loc.start.line}: ${text}`)
        for (const [key, value] of Object.entries(node)) {
            if (key === 'loc' || key === 'range' || key === 'parent') continue
            if (Array.isArray(value)) value.forEach(child => walk(child, silent))
            else if (value && typeof value.type === 'string') walk(value, silent)
        }
    }
    walk(parseSource(source), false)
    return found
}

describe('the exports and the album load do not speak (F98, UAT-308)', () => {
    it.each(FILES)('%s writes no sentence of its own', (file) => {
        const source = fs.readFileSync(path.join(process.cwd(), file), 'utf8')
        expect(sentencesIn(source, WRITTEN_ELSEWHERE[file])).toEqual([])
    })

    it('every sentence allowed is still in its file (the list only shrinks)', () => {
        for (const [file, allowed] of Object.entries(WRITTEN_ELSEWHERE)) {
            const source = fs.readFileSync(path.join(process.cwd(), file), 'utf8')
            const written = sentencesIn(source).map(line => line.replace(/^line \d+: /, ''))
            expect(Object.keys(allowed).filter(text => !written.includes(text)), file).toEqual([])
        }
    })

    describe('the check is not blind (the wrong examples)', () => {
        it('a sentence returned to the caller is accused, with its line', () => {
            const wrong = "export function failureOf() {\n    return { kind: 'error', message: 'No tracks found on Spotify' }\n}\n"
            expect(sentencesIn(wrong)).toEqual(['line 2: No tracks found on Spotify'])
        })

        it('a sentence built with a value in the middle is accused', () => {
            // eslint-disable-next-line no-template-curly-in-string
            const wrong = 'export const holdNotice = (when) => ({ message: `Loading is paused.${when}` })\nexport const say = (title) => `Searching: ${title}`\n'
            expect(sentencesIn(wrong)).toEqual(['line 1: Loading is paused.{}', 'line 2: Searching: {}'])
        })

        it('a sentence told through a callback is accused, one word long too', () => {
            const wrong = "export function start(onProgress) {\n    onProgress('Creating folder...')\n    onProgress('Connecting...')\n}\n"
            expect(sentencesIn(wrong)).toEqual(['line 2: Creating folder...', 'line 3: Connecting...'])
        })

        it('a code, a key of the dictionary, a name of a module, the console and a thrown error are not', () => {
            const right = [
                "import { track } from './usage/track.js'",
                "const KINDS = ['not-found', 'rate-limit', 'spotifyWindow.failure.notFound', 'source_busy', 'MATCHING', 'DeadlineError']",
                "export function run(onProgress) {",
                "    console.warn('[SpotifyExport] Track search failed:', KINDS)",
                "    onProgress({ step: 'connecting' })",
                "    if (!track) throw new Error('No playlists to export')",
                "    return { kind: 'unchecked' }",
                "}"
            ].join('\n')
            expect(sentencesIn(right)).toEqual([])
        })

        it('a sentence that is allowed is not accused, and only that one', () => {
            const source = "export const a = 'Part of the series'\nexport const b = 'Another whole sentence'\n"
            expect(sentencesIn(source, { 'Part of the series': 'a reason' })).toEqual(['line 2: Another whole sentence'])
        })
    })
})
