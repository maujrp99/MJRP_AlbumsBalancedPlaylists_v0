#!/usr/bin/env python3
# cópia carimbada do MJRP Harness · versão 2026-11-21 · fonte d990067a9 · não edite aqui — edite no harness e rode `new_project.py --refresh-kernel`
"""hooks_map_check.py - the judge of the hooks map (F291, S-245): every hook on disk is in `hooks-catalog.json`, and the map cites no hook that is gone.

The rule behind it (orchestrator rule 47, MJRP 2026-11-18): every rule of the orchestrator has a hook and every hook is in the map; a rule that
lives only in the chat or in the agent's memory does not count. The map is the page `docs/wiki/hooks-map.md`, generated by `gen_hooks_map.py`.

    python3 mjrp-scripts/hooks_map_check.py [root]    # exit 0 in step; 1 findings; 2 could not evaluate

Where it runs (the sensor travels to the children, `process_sensors.json`):
  harness  reads its own hooks AND the hooks of every child of the portfolio; fails on a hook missing from the map, on an entry whose hook exists
           nowhere, on a guard of `mjrp-scripts/hooks/` that no settings entry wires, and on a generated page that differs from the disks.
  child    reads its own hooks; fails on a hook missing from the map (the kernel's `hooks-catalog.json` plus its own `hooks-catalog.local.json`) and on
           an unwired guard. The leftover entries of the kernel catalog are not a finding there, and the page is the harness's.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pathlib as _pl, sys as _sys  # noqa: E401  (F73 GV-06: this script's folder on sys.path even when it is loaded by path)
_sys.path[:0] = [d for d in [str(_pl.Path(__file__).resolve().parent)] if d not in _sys.path]
import _boot  # noqa: F401  (the scripts folder on sys.path, F73 R17)
import hooks_map as hm

CONTRACT = ".mjrp-project.yml"


def owns_catalog(root) -> bool:
    """True when the contract says `profile: meta` (the harness): it owns the map and the page."""
    f = Path(root) / CONTRACT
    return f.is_file() and re.search(r"^  profile:\s*[\"']?meta\b", f.read_text(encoding="utf-8"), re.M) is not None


def findings(root) -> list[str] | None:
    """The findings, or None when there is no map to judge."""
    root = Path(root).resolve()
    catalog = hm.load_catalog(root)
    if catalog is None:
        return None
    owner = owns_catalog(root)
    paths = {"este projeto": root}
    if owner:
        import gen_hooks_map as g
        paths = g.projects(root)
    if owner:
        catalog = hm.portfolio_catalog(root, paths.values())
    found = {n: hm.discover(p) for n, p in paths.items()}
    unwired = {n: hm.unwired_guards(p) for n, p in paths.items()}
    out = hm.problems(found, catalog, owner, unwired)
    if owner:
        import gen_hooks_map as g
        step = g.in_step(root)
        if step is False:
            out.append(f"{g.PAGE} difere dos hooks do disco; rode `python3 mjrp-scripts/gen_hooks_map.py`")
    return out


def main(argv) -> int:
    root = Path(argv[1]).resolve() if len(argv) > 1 else Path(__file__).resolve().parent.parent
    try:
        res = findings(root)
    except hm.HooksUnreadable as e:
        print(f"hooks_map_check: não avaliável — o settings existe e não lê ({e})")
        return 2
    except Exception as e:  # noqa: BLE001 - a judge that crashed did not approve
        print(f"hooks_map_check: não avaliável ({type(e).__name__}: {e})")
        return 2
    if res is None:
        print(f"hooks_map_check: sem {hm.CATALOG} em {root} (não avaliável)")
        return 2
    for line in res:
        print(f"  {line}")
    print("hooks_map_check: " + ("todo hook está no mapa e o mapa não cita hook que não existe" if not res else f"{len(res)} problema(s)"))
    return 1 if res else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
