#!/usr/bin/env python3
"""F81 — builds the owner's review page («Revisão de texto do site») from the copy deck.

  python3 design/proposals/copy-review/build_copy_review.py

Reads  design/copy/album-blender-copy.md   (the deck, itself generated by scripts/i18n/build-deck.py)
Fills  copy-review.template.html           (the page; the only place the page is edited by hand)
Writes copy-review.html                    (generated: never edit; published as a private Claude Artifact)

The deck is the single source: the page never carries a text the deck does not have, and an agent
never writes a «final» mark (the page starts with none; the owner clicks them).
"""
import json, pathlib, re, sys

HERE = pathlib.Path(__file__).parent
DECK = HERE.parent.parent / 'copy' / 'album-blender-copy.md'
SPLIT = re.compile(r'(?<!\\)\|')

TYPE_WORDS = {
    'Texto': 'texto na tela', 'Rótulo/opção': 'rótulo ou opção', 'Aviso (toast)': 'aviso rápido', 'Leitor de tela': 'lido só por leitor de tela',
    'Dica (tooltip)/título': 'dica ao passar o mouse', 'Carregando/andamento': 'mensagem de carregando', 'Erro/aviso': 'mensagem de erro',
    'Estado vazio': 'tela ainda vazia', 'Descrição': 'descrição', 'Botão': 'botão', 'Erro (pode chegar à tela)': 'erro técnico',
    'Campo (placeholder)': 'texto dentro do campo', 'Mensagem': 'mensagem', 'Confirmação/aviso do navegador': 'pergunta de confirmação',
    'Título': 'título', 'Mensagem do servidor': 'mensagem do servidor', 'Texto alternativo': 'descrição de imagem', 'Aba do navegador': 'título da aba',
}
SCREEN_NAMES = {'Home (montar a série)': 'Start (montar uma série)', 'Servidor': 'Respostas do servidor', 'Página base (index.html)': 'Página base do site',
                'Conta e conexões (login, Spotify, Apple Music)': 'Conta e conexões', 'Algoritmos e receitas do Blend': 'Receitas do Blend',
                'Componentes comuns (modais, filtros, paginação, avisos)': 'Janelas, filtros e avisos'}
FIRST = ['Página de entrada', 'Start (montar uma série)']


def cells(line):
    parts = [c.strip().replace('\\|', '|') for c in SPLIT.split(line.strip())]
    return parts[1:-1]


def main():
    text = DECK.read_text(encoding='utf-8')
    sections, cur, head = [], None, []
    for line in text.splitlines():
        if line.startswith('## '):
            name = line[3:].strip()
            cur = None if name.startswith('Fora deste mapa') else {'raw': name, 'name': SCREEN_NAMES.get(name, name), 'rows': []}
            if cur: sections.append(cur)
        elif cur is not None and line.startswith('| `'):
            c = cells(line)
            assert len(c) == 12, (len(c), line[:80])
            rid, where, typ, pt, st_pt, en, st_en = c[0].strip('`'), c[1], c[2], c[3], c[4], c[5], c[6]
            note = c[11]
            file = where.rsplit('; `', 1)[1].rstrip() if '; `' in where else ''
            file = ('`' + file) if file and not file.startswith('`') else file
            sections_note = re.sub(r'\bD-\d+\s*', '', note)
            cur['rows'].append({'id': rid, 'where': f"{cur['name']} · {TYPE_WORDS.get(typ, typ.lower())}", 'short': TYPE_WORDS.get(typ, typ.lower()), 'pt': pt, 'en': en, 'type': typ, 'file': file.replace('`', ''),
                                'note': sections_note, 'decide': 'MJRP decide' in note})
    order = {n: i for i, n in enumerate(FIRST)}
    sections.sort(key=lambda s: order.get(s['name'], 99))   # stable: the rest keeps the deck's order
    n = sum(len(s['rows']) for s in sections)
    data = {'source': 'design/copy/album-blender-copy.md', 'total': n, 'sections': sections}
    page = (HERE / 'copy-review.template.html').read_text(encoding='utf-8')
    marker = '/*COPY_DATA*/null'
    assert marker in page
    body = json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
    (HERE / 'copy-review.html').write_text(page.replace(marker, body), encoding='utf-8')
    print(f'{n} linhas em {len(sections)} telas')


if __name__ == '__main__':
    sys.exit(main())
